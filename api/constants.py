def get_flag_url(country_code: str) -> str:
    """Возвращает URL флага по коду страны"""
    if not country_code:
        return ""
    code = country_code.lower()
    code = COUNTRY_CODE_MAP.get(code, code)
    return f"/static/flags/4x3/{code}.svg"


